(function () {
  "use strict";

  var STORAGE_KEY = "gd_lang";

  function getLang() {
    return localStorage.getItem(STORAGE_KEY) || document.documentElement.getAttribute("lang") || "es";
  }

  function apply(lang) {
    var dict = (window.GD_I18N && window.GD_I18N[lang]) || {};
    document.documentElement.setAttribute("lang", lang);

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (dict[key] != null) el.textContent = dict[key];
    });

    document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-html");
      if (dict[key] != null) el.innerHTML = dict[key];
    });

    document.querySelectorAll("[data-i18n-attr]").forEach(function (el) {
      el.getAttribute("data-i18n-attr")
        .split(",")
        .forEach(function (pair) {
          var parts = pair.split(":");
          var attr = parts[0].trim();
          var key = parts[1] && parts[1].trim();
          if (key && dict[key] != null) el.setAttribute(attr, dict[key]);
        });
    });

    document.querySelectorAll(".lang-toggle button").forEach(function (btn) {
      btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
      btn.setAttribute("aria-pressed", btn.getAttribute("data-lang") === lang ? "true" : "false");
    });

    var page = document.body.getAttribute("data-page");
    if (page) {
      if (dict["meta.title." + page]) document.title = dict["meta.title." + page];
      var desc = document.querySelector('meta[name="description"]');
      if (desc && dict["meta.desc." + page]) desc.setAttribute("content", dict["meta.desc." + page]);
    }

    window.dispatchEvent(new CustomEvent("gd-lang-change", { detail: { lang: lang } }));
  }

  function setLang(lang) {
    localStorage.setItem(STORAGE_KEY, lang);
    apply(lang);
  }

  function init() {
    apply(getLang());
    document.querySelectorAll(".lang-toggle button").forEach(function (btn) {
      btn.addEventListener("click", function () { setLang(btn.getAttribute("data-lang")); });
    });
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }

  window.GD_setLang = setLang;
})();
